/**
 * Growth reference curves for ages 0–24 months, closely approximating the
 * WHO Child Growth Standards (percentiles P3 / P15 / P50 / P85 / P97).
 *
 * These values are for at-home visualization only — they are approximations
 * transcribed to one decimal place, not the official LMS tables. Your
 * pediatrician's charts are the clinical reference.
 */

export type Measure = 'weight' | 'length' | 'head'

export const MEASURE_INFO: Record<
  Measure,
  { label: string; shortLabel: string; unit: string; field: 'weightKg' | 'lengthCm' | 'headCm' }
> = {
  weight: { label: 'Weight for age', shortLabel: 'Weight', unit: 'kg', field: 'weightKg' },
  length: { label: 'Length for age', shortLabel: 'Length', unit: 'cm', field: 'lengthCm' },
  head: { label: 'Head circumference for age', shortLabel: 'Head', unit: 'cm', field: 'headCm' },
}

type Row = [month: number, p3: number, p15: number, p50: number, p85: number, p97: number]

function toCurve(rows: Row[]): CurveRow[] {
  return rows.map(([month, p3, p15, p50, p85, p97]) => ({ month, p3, p15, p50, p85, p97 }))
}

/** Head circumference is close to normally distributed: derive percentiles from median + SD */
function symmetric(rows: Array<[month: number, median: number, sd: number]>): CurveRow[] {
  const r1 = (x: number) => Math.round(x * 10) / 10
  return rows.map(([month, m, sd]) => ({
    month,
    p3: r1(m - 1.881 * sd),
    p15: r1(m - 1.036 * sd),
    p50: m,
    p85: r1(m + 1.036 * sd),
    p97: r1(m + 1.881 * sd),
  }))
}

